/**
 * Tipos primitivos en java
 * Tipo	Almacena	Ejemplo
 * byte	Enteros pequeños	byte edad = 20;
 * short	Enteros medianos	short cantidad = 1000;
 * int	Enteros comunes	int numero = 6;
 * long	Enteros grandes	long poblacion = 8000000000L;
 * 
 * float	Decimales con menor precisión	float precio = 3.14f;
 * double	Decimales con mayor precisión	double pi = 3.1416;
 * 
 * char	Un solo carácter	char letra = 'A';
 * String    Cadena de caracteres	String nombre = "Juan";
 * 
 * boolean	true o false	boolean activo = true;
 */

public class _02_TiposDatos
{
    public static void main(String[] args)
    {
        System.out.println("Tipo de dato: int ; "+6); 
        System.out.println("Tipo de dato: double ; "+3.1416);
        System.out.println("Tipo de dato: String ; "+"txt");
        System.out.println("Tipo de dato: boolean ; "+true);
    }
}
