/**
 * Ejemplo de uso de condicional, camino "true" y "false"
 */
public class _02_Condicional2
{
    public static void main(String[] args)
    {
        // Declaramos una variable booleana que controle la condición
        boolean condicion = false;
        
        // Estructura básica de condicional 
        if(condicion) 
        {
            // Ejecutamos si condición devuelve true
            System.out.println("Camino de la verdad");
        }
        else
        {
            // Ejecutamos si condición devuelve false
            System.out.println("Te estoy engañando!!!");
        }
    }
}
