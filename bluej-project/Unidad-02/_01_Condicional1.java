/**
 * Ejemplo de uso de condicional simple, solo el camino "true"
 */
public class _01_Condicional1
{
    public static void main(String[] args)
    {
        // Declaramos una variable booleana que controle la condición
        boolean condicion = false;
        
        // Estructura básica de condicional simple
        if(condicion) 
        {
            // Ejecutamos si condición devuelve true
            System.out.println("Camino de la verdad");
        }
    }
}
